#!/usr/bin/env node
/**
 * build-blog.js
 *
 * Builds the blog from the one-file-per-post source in content/blog/*.json:
 *   1. Rewrites the `posts` list in assets/js/i18n/{en,es}/blog.json
 *      (the blog index and article renderer read from these).
 *   2. Generates a real HTML page per published post: blog/<slug>.html (address /blog/<slug>)
 *      (so search engines and link previews see the content without running JS).
 *   3. Updates the blog post URLs in sitemap.xml between the
 *      <!-- blog-posts:start --> and <!-- blog-posts:end --> markers.
 *
 * Section text is Markdown (lists, tables, links, bold, sub-headings) and is converted to HTML here,
 * so blog.json and the generated pages both carry ready-to-show HTML.
 *
 * Run locally:  npm ci && node scripts/build-blog.js
 * Also run by .github/workflows/build-blog.yml whenever content/blog changes.
 * No dependencies. Safe to run repeatedly: output is deterministic.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const CONTENT_DIR = path.join(ROOT, "content", "blog");
const SITE = "https://oviwellness.com";
const GENERATED_MARK = "<!-- GENERATED by scripts/build-blog.js";

const MONTHS_EN = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
const MONTHS_ES = ["enero", "febrero", "marzo", "abril", "mayo", "junio", "julio", "agosto", "septiembre", "octubre", "noviembre", "diciembre"];

function fail(msg) {
  console.error("build-blog: " + msg);
  process.exit(1);
}

// -- helpers ----------------------------------------------------------------

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (e) {
    fail(`could not read ${path.relative(ROOT, file)}: ${e.message}`);
  }
}

function writeIfChanged(file, text) {
  const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (existing === text) return false;
  fs.writeFileSync(file, text);
  return true;
}

function esc(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

// Display dates match the format the site already used ("August 09, 2026" / "09 de agosto de 2026").
function formatDate(iso, lang) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso || "");
  if (!m) return null;
  const month = parseInt(m[2], 10) - 1;
  if (month < 0 || month > 11) return null;
  return lang === "es"
    ? `${m[3]} de ${MONTHS_ES[month]} de ${m[1]}`
    : `${MONTHS_EN[month]} ${m[3]}, ${m[1]}`;
}

// -- Markdown ---------------------------------------------------------------

let markdown = null;

async function loadMarkdown() {
  let Marked;
  try {
    ({ Marked } = await import("marked"));
  } catch (e) {
    fail('the "marked" package is not installed. Run "npm ci" in the project folder first.');
  }

  // Legacy and absolute links to this site become site-relative; /article?id=x becomes /blog/x.
  function rewriteHref(href) {
    let h = String(href || "");
    h = h.replace(/^https?:\/\/(www\.)?oviwellness\.com\/article\?id=([^&#]+)/i, "/blog/$2");
    h = h.replace(/^https?:\/\/(www\.)?oviwellness\.com(?=\/|$)/i, "") || "/";
    return h;
  }

  markdown = new Marked({
    gfm: true,
    renderer: {
      // Sections already have an <h3> heading, so headings written inside the text sit one level lower.
      heading({ tokens, depth }) {
        const level = Math.min(depth + 1, 6);
        return `<h${level}>${this.parser.parseInline(tokens)}</h${level}>
`;
      },
      link({ href, title, tokens }) {
        const url = rewriteHref(href);
        const external = /^https?:\/\//i.test(url);
        return `<a href="${esc(url)}"${title ? ` title="${esc(title)}"` : ""}${external ? ' target="_blank" rel="noopener noreferrer"' : ""}>${this.parser.parseInline(tokens)}</a>`;
      },
      image({ href, title, text }) {
        return `<img src="${esc(href)}" alt="${esc(text)}"${title ? ` title="${esc(title)}"` : ""} loading="lazy">`;
      },
    },
  });
}

// Section text (Markdown) -> HTML. The first section is the lead paragraph(s) at the top of the post.
function renderBody(text, isLead) {
  let html = markdown.parse(String(text || "").trim()).trim();
  html = html
    .replace(/<table>/g, '<div class="article-table table-responsive"><table class="table">')
    .replace(/<\/table>/g, "</table></div>");
  if (isLead) html = html.replace("<p>", '<p class="lead fw-normal text-dark">');
  return html;
}

function cleanContent(sections) {
  return (Array.isArray(sections) ? sections : []).map((s, i) => {
    const out = { title: s.title || "", body: renderBody(s.body, i === 0) };
    if (hasText(s.image)) out.image = s.image.trim();
    // Kept even without an image: a Spanish section has a description but takes its image from English.
    if (hasText(s.image_alt)) out.imageAlt = s.image_alt.trim();
    return out;
  });
}

function hasText(v) {
  return typeof v === "string" && v.trim() !== "";
}

// Optional SEO fields from the editor. Only set on the post when filled in.
function addSeo(post, src) {
  if (hasText(src.seo_title)) post.seoTitle = src.seo_title.trim();
  if (hasText(src.meta_description)) post.metaDescription = src.meta_description.trim();
  if (hasText(src.featured_image)) post.image = src.featured_image.trim();
  if (hasText(src.featured_image_alt)) post.imageAlt = src.featured_image_alt.trim();
}

function absoluteUrl(p) {
  return /^https?:\/\//.test(p) ? p : SITE + (p.startsWith("/") ? "" : "/") + p;
}

// Services the posts can point to (id -> name and short description, English), from the site's own data.
function loadServices() {
  const map = {};
  for (const s of readJson(path.join(ROOT, "assets", "js", "i18n", "en", "services.json"))) {
    map[s.id] = { tabLabel: s.tabLabel, lead: s.lead || "" };
  }
  return map;
}

// -- load posts -------------------------------------------------------------

function loadPosts() {
  if (!fs.existsSync(CONTENT_DIR)) fail("content/blog does not exist");
  const knownServices = loadServices();
  const posts = [];
  for (const file of fs.readdirSync(CONTENT_DIR).filter((f) => f.endsWith(".json")).sort()) {
    const id = file.replace(/\.json$/, "");
    const src = readJson(path.join(CONTENT_DIR, file));
    if (src.published === false) continue; // draft

    if (!/^[A-Za-z0-9][A-Za-z0-9-]*$/.test(id)) fail(`${file}: file name must be letters, numbers and dashes only`);
    if (!hasText(src.title)) fail(`${file}: missing English title`);
    if (!formatDate(src.date, "en")) fail(`${file}: date must look like 2026-08-14 (got "${src.date}")`);
    if (!Array.isArray(src.content) || src.content.length === 0) fail(`${file}: needs at least one content section`);

    if (hasText(src.service) && !knownServices[src.service.trim()]) {
      fail(`${file}: service "${src.service}" is not a service page (use one of: ${Object.keys(knownServices).join(", ")})`);
    }

    const enPost = {
      id,
      title: src.title.trim(),
      category: (src.category || "").trim(),
      date: formatDate(src.date, "en"),
      excerpt: (src.excerpt || "").trim(),
      content: cleanContent(src.content),
    };
    if (hasText(src.service)) enPost.service = src.service.trim();
    addSeo(enPost, src);

    // Spanish falls back to the English text until a Spanish version is filled in.
    const es = src.es || {};
    const esReady = hasText(es.title) && Array.isArray(es.content) && es.content.length > 0;
    const esPost = {
      id,
      title: esReady ? es.title.trim() : enPost.title,
      category: esReady && hasText(es.category) ? es.category.trim() : enPost.category,
      date: formatDate(src.date, "es"),
      excerpt: esReady && hasText(es.excerpt) ? es.excerpt.trim() : enPost.excerpt,
      content: esReady ? cleanContent(es.content) : enPost.content,
    };
    if (src.show_toc === true) {
      enPost.toc = true;
      esPost.toc = true;
    }
    if (enPost.service) esPost.service = enPost.service;
    // Spanish SEO values fall back to the English ones; the image is shared.
    addSeo(esPost, esReady ? es : src);
    if (!esPost.seoTitle && enPost.seoTitle) esPost.seoTitle = enPost.seoTitle;
    if (!esPost.metaDescription && enPost.metaDescription) esPost.metaDescription = enPost.metaDescription;
    if (enPost.image) {
      esPost.image = enPost.image;
      if (!esPost.imageAlt && enPost.imageAlt) esPost.imageAlt = enPost.imageAlt;
    }
    // Section images come from the English section in the same position; Spanish only adds the description.
    esPost.content.forEach((sec, i) => {
      const enSec = enPost.content[i];
      if (enSec && enSec.image && !sec.image) {
        sec.image = enSec.image;
        if (!sec.imageAlt && enSec.imageAlt) sec.imageAlt = enSec.imageAlt;
      }
    });
    // A description with no image is meaningless; drop it so blog.json stays clean.
    for (const post of [enPost, esPost]) {
      for (const sec of post.content) if (!sec.image) delete sec.imageAlt;
    }

    posts.push({ id, iso: src.date, en: enPost, es: esPost, spanishReady: esReady });
  }
  // Newest first; ties broken by id so output is stable.
  posts.sort((a, b) => (a.iso < b.iso ? 1 : a.iso > b.iso ? -1 : a.id.localeCompare(b.id)));
  return posts;
}

// -- 1. blog.json -----------------------------------------------------------

function buildBlogJson(posts) {
  const changed = [];
  for (const lang of ["en", "es"]) {
    const file = path.join(ROOT, "assets", "js", "i18n", lang, "blog.json");
    const data = readJson(file);
    data.posts = posts.map((p) => p[lang]);
    if (writeIfChanged(file, JSON.stringify(data, null, 2) + "\n")) changed.push(path.relative(ROOT, file));
  }
  return changed;
}

// -- 2. per-post pages ------------------------------------------------------

function replaceOnce(html, regex, replacement, what) {
  if (!regex.test(html)) fail(`article.html template changed: could not find ${what}. Update scripts/build-blog.js.`);
  return html.replace(regex, typeof replacement === "function" ? replacement : () => replacement);
}

// Keep this markup (and the helpers below) identical to what blog-renderer.js builds in the browser.
const RESERVED_IDS = new Set(["consultation", "faqs", "home", "navbar-root", "footer-root", "lower-content"]);

function headingSlug(t) {
  return (
    String(t).toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") ||
    "section"
  );
}

function sectionIds(content) {
  const used = new Set(RESERVED_IDS);
  return content.map((s) => {
    const base = headingSlug(s.title);
    let id = base;
    for (let n = 2; used.has(id); n++) id = base + "-" + n;
    used.add(id);
    return id;
  });
}

// A "Sources" section is styled smaller (see .article-sources in article.html).
function sectionClass(title) {
  return /^(sources|fuentes|references|referencias)\b/i.test(String(title).trim()) ? " article-sources" : "";
}

function tocHtml(post, label) {
  if (!post.toc) return "";
  const ids = sectionIds(post.content);
  const items = post.content
    .map((s, i) => ({ s, id: ids[i], i }))
    .filter(({ s, i }) => i > 0 && s.title && !/^(disclaimer|sources|descargo|fuentes)\b/i.test(s.title.trim()));
  if (items.length < 2) return "";
  return (
    `<nav class="article-toc" aria-label="${esc(label)}"><p class="article-toc-title">${esc(label)}</p><ol>` +
    items.map(({ s, id }) => `<li><a href="#${esc(id)}">${esc(s.title)}</a></li>`).join("") +
    "</ol></nav>"
  );
}

function figure(src, alt, eager) {
  return `<figure class="article-figure"><img src="${esc(src)}" alt="${esc(alt || "")}"${eager ? "" : ' loading="lazy"'}></figure>`;
}

// The "Related service" card goes before any Disclaimer / Sources section, otherwise at the end.
function relatedInsertIndex(content) {
  const i = content.findIndex((s, idx) => idx > 0 && /^(disclaimer|sources|descargo|fuentes|references|referencias)\b/i.test(String(s.title).trim()));
  return i === -1 ? content.length : i;
}

function relatedServiceHtml(post, ctx) {
  const svc = post.service && ctx.services[post.service];
  if (!svc) return "";
  const ui = ctx.ui;
  return (
    `<aside class="article-related-service" aria-label="${esc(ui.relatedService)}"><p class="article-related-label">${esc(ui.relatedService)}</p>` +
    `<a class="article-related-link" href="/services/${esc(post.service)}"><span class="article-related-name">${esc(svc.tabLabel)}</span>` +
    `<span class="article-related-desc">${esc(svc.lead)}</span>` +
    `<span class="article-related-cta">${esc(ui.learnMoreAbout)} ${esc(svc.tabLabel)} &rarr;</span></a></aside>`
  );
}

function renderSections(post, tocLabel, ctx) {
  const featured = post.image ? figure(post.image, post.imageAlt, true) : "";
  const ids = sectionIds(post.content);
  const parts = post.content
    .map((section, index) => {
      const img = section.image ? figure(section.image, section.imageAlt) : "";
      return index === 0
        ? `<div class="article-section">${img}${section.body}</div>`
        : `<div class="article-section${sectionClass(section.title)}">${img}<h3 id="${esc(ids[index])}">${esc(section.title)}</h3>${section.body}</div>`;
    });
  const related = relatedServiceHtml(post, ctx);
  if (related) parts.splice(relatedInsertIndex(post.content), 0, related);
  return featured + tocHtml(post, tocLabel) + parts.join("");
}

function buildPage(template, post, tocLabel, ctx) {
  const en = post.en;
  const url = `${SITE}/blog/${post.id}`;
  const title = en.seoTitle || `${en.title} — OVI Wellness`;
  const desc = en.metaDescription || en.excerpt;
  const image = en.image ? absoluteUrl(en.image) : null;
  let html = template;

  html = replaceOnce(html, /<title>[\s\S]*?<\/title>/, `<title>${esc(title)}</title>`, "<title>");
  html = replaceOnce(html, /<meta name="description" content="[^"]*">/, `<meta name="description" content="${esc(desc)}">`, "meta description");
  html = replaceOnce(html, /<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${url}">`, "canonical link");
  html = replaceOnce(html, /<meta property="og:type" content="[^"]*">/, `<meta property="og:type" content="article">`, "og:type");
  html = replaceOnce(html, /<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${url}">`, "og:url");
  html = replaceOnce(html, /<meta property="og:title" content="[^"]*">/, `<meta property="og:title" content="${esc(title)}">`, "og:title");
  html = replaceOnce(html, /<meta property="og:description" content="[^"]*">/, `<meta property="og:description" content="${esc(desc)}">`, "og:description");
  html = replaceOnce(html, /<meta property="twitter:url" content="[^"]*">/, `<meta property="twitter:url" content="${url}">`, "twitter:url");
  html = replaceOnce(html, /<meta property="twitter:title" content="[^"]*">/, `<meta property="twitter:title" content="${esc(title)}">`, "twitter:title");
  html = replaceOnce(html, /<meta property="twitter:description" content="[^"]*">/, `<meta property="twitter:description" content="${esc(desc)}">`, "twitter:description");
  if (image) {
    html = replaceOnce(html, /<meta property="twitter:card" content="[^"]*">/, `<meta property="twitter:card" content="summary_large_image">`, "twitter:card");
    html = replaceOnce(html, /<meta property="og:description" content="[^"]*">/, (m) => `${m}
    <meta property="og:image" content="${esc(image)}">`, "og:description (image)");
    html = replaceOnce(html, /<meta property="twitter:description" content="[^"]*">/, (m) => `${m}
    <meta property="twitter:image" content="${esc(image)}">`, "twitter:description (image)");
  }

  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "Article",
    headline: en.title,
    description: desc,
    datePublished: post.iso,
    mainEntityOfPage: url,
    ...(image ? { image } : {}),
    publisher: { "@type": "Organization", name: "OVI Wellness", url: SITE },
  };
  html = replaceOnce(
    html,
    /<\/head>/,
    `    <script type="application/ld+json">${JSON.stringify(jsonLd).replace(/</g, "\\u003c")}</script>\n</head>`,
    "</head>"
  );

  html = replaceOnce(html, /<body class="solid-navbar">/, `<body class="solid-navbar" data-article-id="${esc(post.id)}">`, "<body> tag");
  html = replaceOnce(html, /(<span id="articleCategory"[^>]*>)(<\/span>)/, (m, open, close) => open + esc(en.category) + close, "#articleCategory");
  html = replaceOnce(html, /(<h1 id="articleTitle"[^>]*>)(<\/h1>)/, (m, open, close) => open + esc(en.title) + close, "#articleTitle");
  html = replaceOnce(html, /(<span id="articleDate">)(<\/span>)/, (m, open, close) => open + esc(en.date) + close, "#articleDate");
  html = replaceOnce(html, /(<div id="article-sections-container">)(<\/div>)/, (m, open, close) => open + renderSections(en, tocLabel, ctx) + close, "#article-sections-container");

  // The old-address redirect only belongs on the legacy /article page, not on generated post pages.
  html = replaceOnce(html, /[ \t]*<!-- legacy-redirect:start -->[\s\S]*?<!-- legacy-redirect:end -->\r?\n?/, "", "legacy-redirect block");

  // The page lives one folder down (blog/<slug>.html): re-root the template's asset paths, and tell the
  // shared scripts (components.js, main.js, i18n.js) to do the same.
  html = html.replace(/\b(href|src)="assets\//g, '$1="../assets/');
  html = replaceOnce(html, /<script src="\.\.\/assets\/js\/i18n\/i18n\.js/, (m) => `<script>const OVI_BLOG_PAGE = true;</script>\n    ${m}`, "i18n.js script tag");

  // The prerendered text is for crawlers and first paint; blog-renderer.js still takes over in the browser (and for Spanish).
  return html.replace(/<!DOCTYPE html>/i, `<!DOCTYPE html>\n${GENERATED_MARK} from content/blog/${post.id}.json - edit that file, not this one. -->`);
}

function buildPages(posts) {
  const templateFile = path.join(ROOT, "article.html");
  if (!fs.existsSync(templateFile)) fail("article.html (the page template) is missing");
  const template = fs.readFileSync(templateFile, "utf8");
  const enUi = readJson(path.join(ROOT, "assets", "js", "i18n", "en", "blog.json")).ui || {};
  const tocLabel = enUi.tableOfContents || "Table of Contents";
  const ctx = {
    services: loadServices(),
    ui: {
      relatedService: enUi.relatedService || "Related service",
      learnMoreAbout: enUi.learnMoreAbout || "Learn more about",
    },
  };

  const blogDir = path.join(ROOT, "blog");
  const wanted = new Set();
  const changed = [];
  for (const post of posts) {
    const rel = `blog/${post.id}.html`;
    wanted.add(rel);
    fs.mkdirSync(blogDir, { recursive: true });
    if (writeIfChanged(path.join(ROOT, rel), buildPage(template, post, tocLabel, ctx))) changed.push(rel);
  }

  // Remove pages for posts that were deleted or set back to draft (only files this script generated),
  // and pages from the earlier article-<slug>.html address style.
  const removed = [];
  const sweep = (dir, prefix, re) => {
    if (!fs.existsSync(dir)) return;
    for (const f of fs.readdirSync(dir)) {
      const rel = prefix + f;
      if (!re.test(f) || wanted.has(rel)) continue;
      const full = path.join(dir, f);
      if (fs.readFileSync(full, "utf8").includes(GENERATED_MARK)) {
        fs.unlinkSync(full);
        removed.push(rel);
      }
    }
  };
  sweep(blogDir, "blog/", /\.html$/);
  sweep(ROOT, "", /^article-.+\.html$/);
  return { changed, removed };
}

// -- 3. sitemap -------------------------------------------------------------

function buildSitemap(posts) {
  const file = path.join(ROOT, "sitemap.xml");
  const xml = fs.readFileSync(file, "utf8");
  const start = "<!-- blog-posts:start -->";
  const end = "<!-- blog-posts:end -->";
  const a = xml.indexOf(start);
  const b = xml.indexOf(end);
  if (a === -1 || b === -1 || b < a) fail("sitemap.xml is missing the blog-posts:start / blog-posts:end markers");

  const entries = posts
    .map(
      (p) =>
        `  <url>\n    <loc>${SITE}/blog/${p.id}</loc>\n    <lastmod>${p.iso}</lastmod>\n    <priority>0.6</priority>\n    <changefreq>monthly</changefreq>\n  </url>`
    )
    .join("\n");
  const next = xml.slice(0, a + start.length) + (entries ? "\n" + entries + "\n  " : "\n  ") + xml.slice(b);
  return writeIfChanged(file, next) ? ["sitemap.xml"] : [];
}

// -- main -------------------------------------------------------------------

(async () => {
  await loadMarkdown();
  const posts = loadPosts();
  const jsonChanged = buildBlogJson(posts);
  const pages = buildPages(posts);
  const sitemapChanged = buildSitemap(posts);

  // Large images slow the page down; say so instead of failing.
  const heavy = new Set();
  for (const post of posts) {
    const imgs = [post.en.image, ...post.en.content.map((s) => s.image)].filter(Boolean);
    for (const img of imgs) {
      const file = path.join(ROOT, img.replace(/^\//, ""));
      if (fs.existsSync(file) && fs.statSync(file).size > 500 * 1024) heavy.add(`${img} (${(fs.statSync(file).size / 1048576).toFixed(1)} MB)`);
    }
  }

  const spanishPending = posts.filter((p) => !p.spanishReady).map((p) => p.id);
  console.log(`build-blog: ${posts.length} published post(s)`);
  console.log(`  updated: ${[...jsonChanged, ...pages.changed, ...sitemapChanged].join(", ") || "nothing (already up to date)"}`);
  if (pages.removed.length) console.log(`  removed: ${pages.removed.join(", ")}`);
  if (heavy.size) console.log(`  note: large image(s), compress to under about 200 KB for fast pages: ${[...heavy].join(", ")}`);
  if (spanishPending.length) console.log(`  note: no Spanish yet (English shown on /es): ${spanishPending.join(", ")}`);
})();
