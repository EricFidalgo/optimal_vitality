#!/usr/bin/env node
/**
 * build-blog.js
 *
 * Builds the blog from the one-file-per-post source in content/blog/*.json:
 *   1. Rewrites the `posts` list in assets/js/i18n/{en,es}/blog.json
 *      (the blog index and article renderer read from these).
 *   2. Generates a real HTML page per published post: article-<slug>.html
 *      (so search engines and link previews see the content without running JS).
 *   3. Updates the blog post URLs in sitemap.xml between the
 *      <!-- blog-posts:start --> and <!-- blog-posts:end --> markers.
 *
 * Run locally:  node scripts/build-blog.js
 * Also run by .github/workflows/build-blog.yml whenever content/blog changes.
 * No dependencies. Safe to run repeatedly: output is deterministic.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const CONTENT_DIR = path.join(ROOT, "content", "blog");
const SITE = "https://oviwellness.com";
const GENERATED_MARK = "<!-- GENERATED by scripts/build-blog.js";

const MONTHS_EN = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
const MONTHS_ES = ["enero", "febrero", "marzo", "abril", "mayo", "junio", "julio", "agosto", "septiembre", "octubre", "noviembre", "diciembre"];

function fail(msg) {
  console.error("build-blog: " + msg);
  process.exit(1);
}

// -- helpers ----------------------------------------------------------------

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (e) {
    fail(`could not read ${path.relative(ROOT, file)}: ${e.message}`);
  }
}

function writeIfChanged(file, text) {
  const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (existing === text) return false;
  fs.writeFileSync(file, text);
  return true;
}

function esc(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

// Display dates match the format the site already used ("August 09, 2026" / "09 de agosto de 2026").
function formatDate(iso, lang) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso || "");
  if (!m) return null;
  const month = parseInt(m[2], 10) - 1;
  if (month < 0 || month > 11) return null;
  return lang === "es"
    ? `${m[3]} de ${MONTHS_ES[month]} de ${m[1]}`
    : `${MONTHS_EN[month]} ${m[3]}, ${m[1]}`;
}

// Editors can separate paragraphs with a blank line. The renderer wraps a body in one <p>,
// so extra paragraphs are joined with </p><p> to stay valid with the existing markup.
function paragraphs(body) {
  return String(body || "")
    .trim()
    .split(/\n\s*\n/)
    .map((p) => p.replace(/\s*\n\s*/g, " ").trim())
    .filter(Boolean)
    .join("</p><p>");
}

function cleanContent(sections) {
  return (Array.isArray(sections) ? sections : []).map((s) => ({
    title: s.title || "",
    body: paragraphs(s.body),
  }));
}

function hasText(v) {
  return typeof v === "string" && v.trim() !== "";
}

// -- load posts -------------------------------------------------------------

function loadPosts() {
  if (!fs.existsSync(CONTENT_DIR)) fail("content/blog does not exist");
  const posts = [];
  for (const file of fs.readdirSync(CONTENT_DIR).filter((f) => f.endsWith(".json")).sort()) {
    const id = file.replace(/\.json$/, "");
    const src = readJson(path.join(CONTENT_DIR, file));
    if (src.published === false) continue; // draft

    if (!/^[A-Za-z0-9][A-Za-z0-9-]*$/.test(id)) fail(`${file}: file name must be letters, numbers and dashes only`);
    if (!hasText(src.title)) fail(`${file}: missing English title`);
    if (!formatDate(src.date, "en")) fail(`${file}: date must look like 2026-08-14 (got "${src.date}")`);
    if (!Array.isArray(src.content) || src.content.length === 0) fail(`${file}: needs at least one content section`);

    const enPost = {
      id,
      title: src.title.trim(),
      category: (src.category || "").trim(),
      date: formatDate(src.date, "en"),
      excerpt: (src.excerpt || "").trim(),
      content: cleanContent(src.content),
    };

    // Spanish falls back to the English text until a Spanish version is filled in.
    const es = src.es || {};
    const esReady = hasText(es.title) && Array.isArray(es.content) && es.content.length > 0;
    const esPost = {
      id,
      title: esReady ? es.title.trim() : enPost.title,
      category: esReady && hasText(es.category) ? es.category.trim() : enPost.category,
      date: formatDate(src.date, "es"),
      excerpt: esReady && hasText(es.excerpt) ? es.excerpt.trim() : enPost.excerpt,
      content: esReady ? cleanContent(es.content) : enPost.content,
    };

    posts.push({ id, iso: src.date, en: enPost, es: esPost, spanishReady: esReady });
  }
  // Newest first; ties broken by id so output is stable.
  posts.sort((a, b) => (a.iso < b.iso ? 1 : a.iso > b.iso ? -1 : a.id.localeCompare(b.id)));
  return posts;
}

// -- 1. blog.json -----------------------------------------------------------

function buildBlogJson(posts) {
  const changed = [];
  for (const lang of ["en", "es"]) {
    const file = path.join(ROOT, "assets", "js", "i18n", lang, "blog.json");
    const data = readJson(file);
    data.posts = posts.map((p) => p[lang]);
    if (writeIfChanged(file, JSON.stringify(data, null, 2) + "\n")) changed.push(path.relative(ROOT, file));
  }
  return changed;
}

// -- 2. per-post pages ------------------------------------------------------

function replaceOnce(html, regex, replacement, what) {
  if (!regex.test(html)) fail(`article.html template changed: could not find ${what}. Update scripts/build-blog.js.`);
  return html.replace(regex, typeof replacement === "function" ? replacement : () => replacement);
}

function renderSections(content) {
  return content
    .map((section, index) =>
      index === 0
        ? `<div class="article-section"><p class="lead fw-normal text-dark">${section.body}</p></div>`
        : `<div class="article-section"><h3>${esc(section.title)}</h3><p>${section.body}</p></div>`
    )
    .join("");
}

function buildPage(template, post) {
  const en = post.en;
  const url = `${SITE}/article-${post.id}`;
  const title = `${en.title} — OVI Wellness`;
  const desc = en.excerpt;
  let html = template;

  html = replaceOnce(html, /<title>[\s\S]*?<\/title>/, `<title>${esc(title)}</title>`, "<title>");
  html = replaceOnce(html, /<meta name="description" content="[^"]*">/, `<meta name="description" content="${esc(desc)}">`, "meta description");
  html = replaceOnce(html, /<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${url}">`, "canonical link");
  html = replaceOnce(html, /<meta property="og:type" content="[^"]*">/, `<meta property="og:type" content="article">`, "og:type");
  html = replaceOnce(html, /<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${url}">`, "og:url");
  html = replaceOnce(html, /<meta property="og:title" content="[^"]*">/, `<meta property="og:title" content="${esc(title)}">`, "og:title");
  html = replaceOnce(html, /<meta property="og:description" content="[^"]*">/, `<meta property="og:description" content="${esc(desc)}">`, "og:description");
  html = replaceOnce(html, /<meta property="twitter:url" content="[^"]*">/, `<meta property="twitter:url" content="${url}">`, "twitter:url");
  html = replaceOnce(html, /<meta property="twitter:title" content="[^"]*">/, `<meta property="twitter:title" content="${esc(title)}">`, "twitter:title");
  html = replaceOnce(html, /<meta property="twitter:description" content="[^"]*">/, `<meta property="twitter:description" content="${esc(desc)}">`, "twitter:description");

  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "Article",
    headline: en.title,
    description: desc,
    datePublished: post.iso,
    mainEntityOfPage: url,
    publisher: { "@type": "Organization", name: "OVI Wellness", url: SITE },
  };
  html = replaceOnce(
    html,
    /<\/head>/,
    `    <script type="application/ld+json">${JSON.stringify(jsonLd).replace(/</g, "\\u003c")}</script>\n</head>`,
    "</head>"
  );

  html = replaceOnce(html, /<body class="solid-navbar">/, `<body class="solid-navbar" data-article-id="${esc(post.id)}">`, "<body> tag");
  html = replaceOnce(html, /(<span id="articleCategory"[^>]*>)(<\/span>)/, (m, open, close) => open + esc(en.category) + close, "#articleCategory");
  html = replaceOnce(html, /(<h1 id="articleTitle"[^>]*>)(<\/h1>)/, (m, open, close) => open + esc(en.title) + close, "#articleTitle");
  html = replaceOnce(html, /(<span id="articleDate">)(<\/span>)/, (m, open, close) => open + esc(en.date) + close, "#articleDate");
  html = replaceOnce(html, /(<div id="article-sections-container">)(<\/div>)/, (m, open, close) => open + renderSections(en.content) + close, "#article-sections-container");

  // The prerendered text is for crawlers and first paint; blog-renderer.js still takes over in the browser (and for Spanish).
  return html.replace(/<!DOCTYPE html>/i, `<!DOCTYPE html>\n${GENERATED_MARK} from content/blog/${post.id}.json - edit that file, not this one. -->`);
}

function buildPages(posts) {
  const templateFile = path.join(ROOT, "article.html");
  if (!fs.existsSync(templateFile)) fail("article.html (the page template) is missing");
  const template = fs.readFileSync(templateFile, "utf8");

  const wanted = new Set();
  const changed = [];
  for (const post of posts) {
    const name = `article-${post.id}.html`;
    wanted.add(name);
    if (writeIfChanged(path.join(ROOT, name), buildPage(template, post))) changed.push(name);
  }

  // Remove pages for posts that were deleted or set back to draft (only files this script generated).
  const removed = [];
  for (const f of fs.readdirSync(ROOT)) {
    if (!/^article-.+\.html$/.test(f) || wanted.has(f)) continue;
    const full = path.join(ROOT, f);
    if (fs.readFileSync(full, "utf8").includes(GENERATED_MARK)) {
      fs.unlinkSync(full);
      removed.push(f);
    }
  }
  return { changed, removed };
}

// -- 3. sitemap -------------------------------------------------------------

function buildSitemap(posts) {
  const file = path.join(ROOT, "sitemap.xml");
  const xml = fs.readFileSync(file, "utf8");
  const start = "<!-- blog-posts:start -->";
  const end = "<!-- blog-posts:end -->";
  const a = xml.indexOf(start);
  const b = xml.indexOf(end);
  if (a === -1 || b === -1 || b < a) fail("sitemap.xml is missing the blog-posts:start / blog-posts:end markers");

  const entries = posts
    .map(
      (p) =>
        `  <url>\n    <loc>${SITE}/article-${p.id}</loc>\n    <lastmod>${p.iso}</lastmod>\n    <priority>0.6</priority>\n    <changefreq>monthly</changefreq>\n  </url>`
    )
    .join("\n");
  const next = xml.slice(0, a + start.length) + (entries ? "\n" + entries + "\n  " : "\n  ") + xml.slice(b);
  return writeIfChanged(file, next) ? ["sitemap.xml"] : [];
}

// -- main -------------------------------------------------------------------

const posts = loadPosts();
const jsonChanged = buildBlogJson(posts);
const pages = buildPages(posts);
const sitemapChanged = buildSitemap(posts);

const spanishPending = posts.filter((p) => !p.spanishReady).map((p) => p.id);
console.log(`build-blog: ${posts.length} published post(s)`);
console.log(`  updated: ${[...jsonChanged, ...pages.changed, ...sitemapChanged].join(", ") || "nothing (already up to date)"}`);
if (pages.removed.length) console.log(`  removed: ${pages.removed.join(", ")}`);
if (spanishPending.length) console.log(`  note: no Spanish yet (English shown on /es): ${spanishPending.join(", ")}`);
